-- Student Management System - Oracle schema
-- Run as the student_app user (Oracle 12c or newer, needed for IDENTITY columns).

-- To reset everything, uncomment these lines first:
-- DROP TABLE STUDENTS CASCADE CONSTRAINTS;
-- DROP TABLE DEPARTMENTS CASCADE CONSTRAINTS;
-- DROP TABLE ADMIN_USERS CASCADE CONSTRAINTS;

CREATE TABLE DEPARTMENTS (
    DEPARTMENT_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    DEPARTMENT_NAME VARCHAR2(100) NOT NULL,
    DEPARTMENT_CODE VARCHAR2(10)  NOT NULL,
    CONSTRAINT UK_DEPARTMENT_CODE UNIQUE (DEPARTMENT_CODE)
);

CREATE TABLE STUDENTS (
    STUDENT_ID    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FIRST_NAME    VARCHAR2(50)  NOT NULL,
    LAST_NAME     VARCHAR2(50)  NOT NULL,
    EMAIL         VARCHAR2(100) NOT NULL,
    PHONE         VARCHAR2(10)  NOT NULL,
    DATE_OF_BIRTH DATE,
    GENDER        VARCHAR2(10),
    DEPARTMENT_ID NUMBER NOT NULL,
    YEAR_OF_STUDY NUMBER(1) NOT NULL,
    CGPA          NUMBER(4,2) NOT NULL,
    ADDRESS       VARCHAR2(255),
    CITY          VARCHAR2(50),
    STATE         VARCHAR2(50),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_STUDENT_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_STUDENT_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID)
        REFERENCES DEPARTMENTS (DEPARTMENT_ID),
    CONSTRAINT CK_STUDENT_YEAR CHECK (YEAR_OF_STUDY BETWEEN 1 AND 4),
    CONSTRAINT CK_STUDENT_CGPA CHECK (CGPA BETWEEN 0 AND 10)
);

CREATE TABLE ADMIN_USERS (
    ADMIN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50)  NOT NULL,
    PASSWORD VARCHAR2(100) NOT NULL,   -- BCrypt hash, never plain text
    ROLE     VARCHAR2(20)  NOT NULL,
    CONSTRAINT UK_ADMIN_USERNAME UNIQUE (USERNAME)
);

CREATE INDEX IDX_STUDENT_DEPARTMENT ON STUDENTS (DEPARTMENT_ID);
CREATE INDEX IDX_STUDENT_YEAR ON STUDENTS (YEAR_OF_STUDY);
